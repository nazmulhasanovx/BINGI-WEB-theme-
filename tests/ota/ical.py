# iCal calendar sync UI (prototype) — Settings › Website & channels.
import re, sys
from playwright.sync_api import sync_playwright
B="http://localhost:3100"; R=[]
def t(n,ok,d=""): R.append(ok); print(("PASS " if ok else "FAIL ")+n, "" if ok else d)
with sync_playwright() as p:
  b=p.chromium.launch()
  for w in (1280,390):
    pg=b.new_page(viewport={"width":w,"height":900}); errs=[]; pg.on("pageerror",lambda e: errs.append(str(e)))
    pg.goto(B+"/hms"); pg.evaluate("localStorage.clear(); localStorage.setItem('hms-property','sea-pearl')")
    pg.goto(B+"/hms/settings/channels"); pg.wait_for_timeout(1800)
    card=pg.get_by_role("region",name="Calendar sync (iCal)")
    t(f"[{w}] card + truth label", card.is_visible() and "Prototype · not live" in card.inner_text())
    t(f"[{w}] dates-only note", "Dates only" in card.inner_text())
    btn=card.get_by_role("button",name=re.compile("^Calendar for room")).first
    room=btn.get_attribute("aria-label").replace("Calendar for ","")
    btn.click(); pg.wait_for_timeout(300)
    dlg=pg.get_by_role("dialog",name=re.compile("Calendar sync"))
    t(f"[{w}] sheet opens", dlg.is_visible())
    pg.context.grant_permissions(["clipboard-read","clipboard-write"])
    dlg.get_by_role("button",name="Copy").click(); pg.wait_for_timeout(200)
    link=dlg.get_by_label(re.compile("BinGi calendar link")).input_value()
    t(f"[{w}] export link made", link.startswith("https://bingi.app/ical/sea-pearl/") and ".ics?k=" in link, link)
    t(f"[{w}] copied state", dlg.get_by_role("button",name="Copied").count()==1)
    inp=dlg.get_by_label("Calendar link from the other site")
    for bad,msg in [("","Paste"),("hello","not a web link"),("https://example.com/page","not look like a calendar"),(link,"BinGi link")]:
      inp.fill(bad); dlg.get_by_role("button",name="Add",exact=True).click(); pg.wait_for_timeout(100)
      a=dlg.get_by_role("alert"); t(f"[{w}] reject {bad[:20]!r}", a.count()==1 and msg in a.inner_text(), a.inner_text() if a.count() else "no alert")
    air="https://www.airbnb.com/calendar/ical/123456.ics?s=abc"
    inp.fill(air); t(f"[{w}] auto-detect Airbnb", dlg.get_by_label("Which site").input_value()=="Airbnb")
    dlg.get_by_role("button",name="Add",exact=True).click(); pg.wait_for_timeout(200)
    t(f"[{w}] feed added", dlg.get_by_role("button",name="Remove Airbnb calendar").count()==1)
    inp.fill(air); dlg.get_by_role("button",name="Add",exact=True).click(); pg.wait_for_timeout(100)
    t(f"[{w}] duplicate rejected", "already added" in dlg.get_by_role("alert").inner_text())
    inp.fill("https://admin.booking.com/hotel/hoteladmin/ical.html?t=xyz"); dlg.get_by_role("button",name="Add",exact=True).click(); pg.wait_for_timeout(200)
    t(f"[{w}] booking.com added", dlg.get_by_role("button",name="Remove Booking.com calendar").count()==1)
    dlg.get_by_role("tab",name="Vrbo").click(); t(f"[{w}] how-to tabs", "Vrbo ›" in dlg.inner_text())
    dlg.get_by_role("button",name="Done").click(); pg.wait_for_timeout(300)
    row=card.get_by_role("button",name=f"Calendar for {room}")
    t(f"[{w}] row shows linked + Manage", row.inner_text()=="Manage" and "Airbnb" in card.inner_text() and "1 of" in card.inner_text())
    pg.reload(); pg.wait_for_timeout(1800)
    t(f"[{w}] persists", pg.get_by_role("button",name=f"Calendar for {room}").inner_text()=="Manage")
    pg.get_by_role("button",name=f"Calendar for {room}").click(); pg.wait_for_timeout(300)
    dlg=pg.get_by_role("dialog",name=re.compile("Calendar sync"))
    t(f"[{w}] same link after reload", dlg.get_by_label(re.compile("BinGi calendar link")).input_value()==link)
    dlg.get_by_role("button",name="Remove Airbnb calendar").click(); pg.wait_for_timeout(200)
    t(f"[{w}] remove works", dlg.get_by_role("button",name="Remove Airbnb calendar").count()==0)
    pg.keyboard.press("Escape"); pg.mouse.click(5,5); pg.wait_for_timeout(300)
    pg.once("dialog", lambda d: d.accept())
    pg.get_by_role("button",name="Renew all links").click(); pg.wait_for_timeout(300)
    pg.get_by_role("button",name=f"Calendar for {room}").click(); pg.wait_for_timeout(300)
    nl=pg.get_by_role("dialog",name=re.compile("Calendar sync")).get_by_label(re.compile("BinGi calendar link")).input_value()
    t(f"[{w}] renew makes new link", nl!=link and ".ics?k=" in nl)
    if w==390: pg.screenshot(path="/tmp/ical_m.png")
    else:
      pg.screenshot(path="/tmp/ical_sheet.png"); pg.mouse.click(5,5); pg.wait_for_timeout(300); card.screenshot(path="/tmp/ical_card.png")
    t(f"[{w}] no page errors", not errs, errs)
    pg.close()
  b.close()
print("ALL PASS" if all(R) else f"FAILED {R.count(False)}")
